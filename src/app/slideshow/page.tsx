"use client";

import Link from "next/link";
import { useCallback, useEffect, useRef, useState } from "react";
import { ArrowLeft, ChevronLeft, ChevronRight, Maximize, Minimize, Pause, Play } from "lucide-react";
import { useApp } from "@/context/AppContext";
import QRCode from "@/components/QRCode";
import { api, ApiError, openStream, photoSrc, type Photo, type StreamMessage, type WeddingEvent } from "@/lib/api";
import { clockTime, eventName } from "@/lib/format";
import styles from "./slideshow.module.css";

const DURATIONS = [5000, 8000, 12000];
const URL_REFRESH_MS = 10 * 60 * 1000;

/**
 * Live Wall for the venue screen. Access comes from a read-only display
 * link (/slideshow/?k=…) generated by the host or admin — never the host
 * token. The key is exchanged for an HttpOnly cookie and removed from the URL.
 */
export default function SlideshowPage() {
  const { setEvent } = useApp();
  const [access, setAccess] = useState<"checking" | "ok" | "denied">("checking");
  const [event, setWallEvent] = useState<WeddingEvent | null>(null);
  const [photos, setPhotos] = useState<Photo[]>([]);
  const [incoming, setIncoming] = useState<Photo | null>(null);
  const [qrUrl, setQrUrl] = useState("");

  const load = useCallback(async () => {
    const [ev, ph] = await Promise.all([api.display.event(), api.display.photos()]);
    setWallEvent(ev);
    setEvent(ev);
    setPhotos(ph.photos);
    return ph.photos;
  }, [setEvent]);

  // exchange ?k= for a display cookie, then load
  useEffect(() => {
    (async () => {
      const params = new URLSearchParams(window.location.search);
      const k = params.get("k");
      try {
        if (k) {
          window.history.replaceState(null, "", window.location.pathname);
          await api.display.session(k);
        }
        await load();
        setAccess("ok");
      } catch (err) {
        setAccess(err instanceof ApiError && err.status !== 0 ? "denied" : "checking");
      }
    })();
  }, [load]);

  // realtime + periodic refresh of signed URLs
  useEffect(() => {
    if (access !== "ok") return;
    let debounce: ReturnType<typeof setTimeout> | null = null;
    let want: string | null = null;
    const reload = () => {
      if (debounce) clearTimeout(debounce);
      debounce = setTimeout(async () => {
        const id = want;
        want = null;
        try {
          const list = await load();
          const p = id ? list.find((x) => x.id === id) : undefined;
          if (p) setIncoming(p);
        } catch {
          /* keep showing what we have */
        }
      }, 400);
    };
    const es = openStream("wall");
    es.onmessage = (e) => {
      let msg: StreamMessage;
      try {
        msg = JSON.parse(e.data);
      } catch {
        return;
      }
      if (msg.type === "photo.published") want = msg.data.id;
      if (msg.type === "photo.removed" && msg.data.from !== "gallery") setPhotos((prev) => prev.filter((p) => p.id !== msg.data.id));
      if (msg.type === "photo.liked") return;
      reload();
    };
    const timer = setInterval(reload, URL_REFRESH_MS);
    return () => {
      es.close();
      clearInterval(timer);
      if (debounce) clearTimeout(debounce);
    };
  }, [access, load]);

  // check-in QR (fixed per event, re-polled in case it is rotated); hidden while the booth is closed
  useEffect(() => {
    if (access !== "ok" || !event?.photoboothOpen) {
      // eslint-disable-next-line react-hooks/set-state-in-effect -- hide stale QR when the booth closes
      setQrUrl("");
      return;
    }
    let alive = true;
    let timer: ReturnType<typeof setTimeout>;
    const tick = async () => {
      try {
        const qr = await api.display.qr();
        if (!alive) return;
        setQrUrl(qr.url);
        timer = setTimeout(tick, Math.max(30000, qr.refreshAfterMs));
      } catch {
        if (!alive) return;
        setQrUrl("");
        timer = setTimeout(tick, 60000);
      }
    };
    tick();
    return () => {
      alive = false;
      clearTimeout(timer);
    };
  }, [access, event?.photoboothOpen]);

  const [index, setIndex] = useState(0);
  const [playing, setPlaying] = useState(true);
  const [duration, setDuration] = useState(8000);
  const [fullscreen, setFullscreen] = useState(false);
  const [idle, setIdle] = useState(false);
  const [freshId, setFreshId] = useState<string | null>(null);
  const rootRef = useRef<HTMLDivElement>(null);

  const count = photos.length;
  const safeIndex = count ? index % count : 0;
  const photo = photos[safeIndex];

  const next = useCallback(() => setIndex((i) => (count ? (i + 1) % count : 0)), [count]);
  const prev = useCallback(() => setIndex((i) => (count ? (i - 1 + count) % count : 0)), [count]);

  const toggleFullscreen = useCallback(() => {
    if (!document.fullscreenElement) rootRef.current?.requestFullscreen().catch(() => undefined);
    else document.exitFullscreen().catch(() => undefined);
  }, []);

  // Auto-advance (restarts whenever the slide changes)
  useEffect(() => {
    if (!playing || count < 2) return;
    const t = setTimeout(next, duration);
    return () => clearTimeout(t);
  }, [playing, count, duration, next, safeIndex]);

  // Jump straight to brand-new photos so guests see theirs immediately.
  useEffect(() => {
    if (!incoming) return;
    const i = photos.findIndex((p) => p.id === incoming.id);
    if (i < 0) return;
    // eslint-disable-next-line react-hooks/set-state-in-effect -- reacting to a server push
    setIndex(i);
    setFreshId(incoming.id);
    const t = setTimeout(() => setFreshId(null), duration);
    return () => clearTimeout(t);
    // eslint-disable-next-line react-hooks/exhaustive-deps -- only when a new photo arrives
  }, [incoming]);

  // Keyboard + fullscreen + auto-hide controls
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "ArrowRight") next();
      if (e.key === "ArrowLeft") prev();
      if (e.key === " ") {
        e.preventDefault();
        setPlaying((p) => !p);
      }
      if (e.key.toLowerCase() === "f") toggleFullscreen();
    };
    const onFs = () => setFullscreen(!!document.fullscreenElement);
    let idleTimer: ReturnType<typeof setTimeout>;
    const onMove = () => {
      setIdle(false);
      clearTimeout(idleTimer);
      idleTimer = setTimeout(() => setIdle(true), 3000);
    };
    onMove();
    document.addEventListener("keydown", onKey);
    document.addEventListener("fullscreenchange", onFs);
    document.addEventListener("mousemove", onMove);
    document.addEventListener("touchstart", onMove);
    return () => {
      clearTimeout(idleTimer);
      document.removeEventListener("keydown", onKey);
      document.removeEventListener("fullscreenchange", onFs);
      document.removeEventListener("mousemove", onMove);
      document.removeEventListener("touchstart", onMove);
    };
  }, [next, prev, toggleFullscreen]);

  if (access !== "ok" || !event) {
    return (
      <div ref={rootRef} className={styles.root}>
        <div className={styles.empty}>
          {access === "checking" ? (
            <span className="spinner" />
          ) : (
            <>
              <h2 className="serif-italic">Live Wall</h2>
              <p>Layar ini hanya dapat dibuka dari link Live Wall yang dibagikan tuan rumah untuk layar acara.</p>
              <Link href="/photobooth" className="btn btn-light btn-sm">
                <ArrowLeft /> Kembali
              </Link>
            </>
          )}
        </div>
      </div>
    );
  }

  return (
    <div ref={rootRef} className={`${styles.root} ${idle ? styles.idle : ""}`}>
      {photo && <div key={`bg-${photo.id}`} className={styles.backdrop} style={{ backgroundImage: `url(${photoSrc(photo.thumbUrl || photo.photoUrl)})` }} />}

      <header className={styles.top}>
        <div className={styles.brand}>
          <span className="serif-italic">
            {eventName(event)}
          </span>
          {event.hashtag && <small>{event.hashtag}</small>}
        </div>
        <span className="badge badge-live">
          <span className="live-dot" /> Live Photo Wall
        </span>
      </header>

      {photo ? (
        <div className={styles.stage} key={`stage-${photo.id}`}>
          <div className={styles.photoWrap}>
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={photoSrc(photo.photoUrl)} alt={`Foto dari ${photo.guestName}`} className={styles.photo} />
            {freshId === photo.id && <span className={styles.fresh}>Baru masuk!</span>}
          </div>
          <div className={styles.wish}>
            <span className={styles.quoteMark}>&ldquo;</span>
            <p className={styles.wishText}>{photo.wishes}</p>
            <div className={styles.from}>
              <span className={styles.avatar}>{photo.guestName.trim()[0]?.toUpperCase()}</span>
              <div>
                <strong>{photo.guestName}</strong>
                <small>{clockTime(photo.createdAt)}</small>
              </div>
            </div>
          </div>
        </div>
      ) : (
        <div className={styles.empty}>
          <h2 className="serif-italic">Belum ada foto</h2>
          <p>{qrUrl ? "Scan QR di pojok kanan bawah untuk mengirim foto pertama!" : "Foto dari photobooth akan tampil di sini."}</p>
        </div>
      )}

      {/* progress */}
      {photo && playing && count > 1 && (
        <div className={styles.progress} key={`${photo.id}-${duration}`}>
          <span style={{ animationDuration: `${duration}ms` }} />
        </div>
      )}

      <footer className={styles.bottom}>
        <div className={styles.counter}>
          {count > 0 && (
            <>
              <strong>{safeIndex + 1}</strong> / {count} foto
            </>
          )}
        </div>

        <div className={styles.controls}>
          <Link href="/photobooth" className="icon-btn" aria-label="Kembali">
            <ArrowLeft />
          </Link>
          <button className="icon-btn" onClick={prev} aria-label="Sebelumnya">
            <ChevronLeft />
          </button>
          <button className="icon-btn" onClick={() => setPlaying((p) => !p)} aria-label={playing ? "Jeda" : "Putar"}>
            {playing ? <Pause /> : <Play />}
          </button>
          <button className="icon-btn" onClick={next} aria-label="Berikutnya">
            <ChevronRight />
          </button>
          <div className={styles.durations}>
            {DURATIONS.map((d) => (
              <button key={d} className={d === duration ? styles.durActive : ""} onClick={() => setDuration(d)}>
                {d / 1000}s
              </button>
            ))}
          </div>
          <button className="icon-btn" onClick={toggleFullscreen} aria-label="Layar penuh">
            {fullscreen ? <Minimize /> : <Maximize />}
          </button>
        </div>

        {qrUrl && (
          <div className={styles.qr}>
            <div>
              <strong>Photobooth</strong>
              <small>Scan di lokasi acara</small>
            </div>
            <QRCode value={qrUrl} size={96} className={styles.qrImg} />
          </div>
        )}
      </footer>
    </div>
  );
}
